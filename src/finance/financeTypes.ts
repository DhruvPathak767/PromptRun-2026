/**
 * Distinguishes flow direction and classification of ledger entries.
 */
export type TransactionType = 'expense' | 'income' | 'savings_transfer' | 'bill_payment'

/**
 * An immutable ledger entry recording a cash flow event within the 30-day cycle.
 */
export interface Transaction {
  /** Unique transaction identifier (UUID or timestamp hash) */
  id: string
  /** Cycle day on which the transaction occurred (1-30) */
  cycleDay: number
  /** User-friendly formatted date string (e.g., 'Day 8 • Oct 18') */
  date: string
  /** Transaction amount in INR (always positive integer) */
  amount: number
  /** Short text description of the expense or credit */
  description: string
  /** Category taxonomy classification */
  category: ExpenseCategory
  /** Ledger classification type */
  type: TransactionType
  /** True if fixed recurring obligation/bill; false if discretionary variable spend */
  isFixed: boolean
  /** Optional user notes or annotations */
  note?: string
  /** Foreign key pointing to related commitment or goal ID if applicable */
  relatedId?: string
}

/**
 * Scheduled recurring or one-time payment obligation due on a specific cycle day.
 */
export interface Commitment {
  /** Unique commitment identifier */
  id: string
  /** Name of the bill or obligation (e.g. 'Hostel WiFi', 'Room Rent') */
  name: string
  /** Due amount in INR */
  amount: number
  /** Due date within the cycle (1-30) */
  dueDay: number
  /** Categorization */
  category: ExpenseCategory
  /** Payment status flag */
  isPaid: boolean
  /** Cycle day on which payment was settled */
  paidOnDay?: number
  /** Transaction ID created upon payment settlement */
  paidTransactionId?: string
  /** Link to parent subscription service if generated by recurring rule */
  relatedSubscriptionId?: string
}

/**
 * Recurring digital or physical subscription service requiring monthly budgeting.
 */
export interface Subscription {
  /** Unique subscription identifier */
  id: string
  /** Service brand name (e.g. 'Spotify Student', 'ChatGPT Plus') */
  name: string
  /** Monthly billing rate in INR */
  price: number
  /** Day of the month billing recurs (1-30) */
  billingDay: number
  /** Categorization */
  category: ExpenseCategory
  /** Active status; when false, service is paused and no future charges reserve cash */
  active: boolean
  /** Optional tier description (e.g. 'Student Plan') */
  tier?: string
  /** Optional brand icon asset reference */
  serviceIcon?: string
}

/**
 * Dedicated savings vault reserving liquidity toward a specific milestone.
 */
export interface SavingsGoal {
  /** Unique goal identifier */
  id: string
  /** Goal name (e.g. 'Emergency Buffer', 'Concert Ticket') */
  name: string
  /** Target financial objective in INR */
  targetAmount: number
  /** Current funds locked in vault in INR */
  currentAmount: number
  /** Monthly contribution planned for this 30-day cycle */
  plannedCycleContribution: number
  /** Accent color hex code */
  color: string
  /** Goal domain category */
  category: string
  /** Lucide icon identifier */
  iconName: string
  /** Description or purpose of the savings goal */
  description: string
}

/**
 * Supported types of hypothetical simulation scenarios in the What-If Lab.
 */
export type SimulatedScenarioType =
  | 'purchase'
  | 'add_subscription'
  | 'cancel_subscription'
  | 'unexpected_expense'
  | 'savings_contribution'
  | 'add_income'
  | 'add_commitment'
  | 'adjust_savings_plan'

/**
 * Hypothetical simulation payload tested non-destructively before committing.
 */
export interface SimulatedScenario {
  /** Unique scenario identifier */
  id: string
  /** Scenario category classification */
  type: SimulatedScenarioType
  /** Display title */
  title: string
  /** Rationale or explanation */
  description: string
  /** Financial impact amount in INR */
  amount: number
  /** Optional category */
  category?: ExpenseCategory
  /** Optional cycle day */
  dueDay?: number
  /** Target goal ID for savings adjustments */
  targetGoalId?: string
  /** Target subscription ID for subscription adjustments */
  targetSubscriptionId?: string
  /** User notes */
  customNotes?: string
}

/**
 * High-level classification band summarizing overall financial posture.
 */
export type HealthBand = 'Healthy' | 'Needs Attention' | 'High Risk'

/**
 * Individual score contributor contributing to the composite 0-100 Financial Health Score.
 */
export interface HealthFactor {
  /** Name of the scored dimension */
  name: string
  /** Score awarded in this dimension */
  score: number
  /** Maximum possible score */
  maxScore: number
  /** Plain-English explanation of deduction or reward */
  explanation: string
  /** Status grade */
  status: 'good' | 'warning' | 'critical'
}

/**
 * Comprehensive derived metrics container generated deterministically from FinanceState.
 */
export interface FinancialMetrics {
  /** Fixed starting cycle capital (₹10,000) */
  openingBudget: number
  /** Active simulation cycle day (1-30) */
  currentDay: number
  /** Sum of all income credits recorded */
  totalIncome: number
  /** Sum of all debit expenses recorded */
  totalExpenses: number
  /** Sum of liquid transfers moved into savings vaults */
  totalSavingsTransfers: number
  /** Available liquid cash balance in hand */
  cashBalance: number
  /** Total funds locked across all savings goals */
  savingsBalance: number
  /** Net total capital (cashBalance + savingsBalance) */
  totalRemainingFunds: number
  /** Total unpaid scheduled obligations remaining in cycle */
  upcomingCommitmentsTotal: number
  /** Count of unpaid scheduled obligations */
  upcomingCommitmentsCount: number
  /** Outstanding cycle savings allocations remaining */
  outstandingPlannedSavingsTotal: number
  /** True discretionary living buffer after subtracting commitments & savings */
  availableDiscretionaryFunds: number
  /** Days remaining until cycle completion (exclusive) */
  daysRemaining: number
  /** Days remaining inclusive of current day (1 to 30) */
  inclusiveDaysRemaining: number
  /** Sustainable daily spending rate per remaining day */
  safeDailyAllowance: number
  /** Projected liquid balance at Day 30 under current pace */
  projectedMonthEndCash: number
  /** Actual historical burn rate per elapsed day */
  variableSpendPerElapsedDay: number
  /** Estimated discretionary spend remaining under current burn */
  estimatedRemainingVariableSpend: number
  /** Algorithmic financial health score (0-100) */
  healthScore: number
  /** Health rating classification band */
  healthBand: HealthBand
  /** Primary health status color */
  healthColor: string
  /** Granular diagnostic factors composing health score */
  healthFactors: HealthFactor[]
  /** Pacing trajectory indicators */
  spendingPace: {
    actualDailyAverage: number
    targetDailyPace: number
    paceRatio: number
    status: 'under_budget' | 'on_track' | 'over_budget'
  }
  /** Category-by-category breakdown with percentages */
  categoryBreakdown: Array<{
    category: ExpenseCategory
    amount: number
    percentage: number
    color: string
    count: number
  }>
  /** 30-day timeline series for projection charts */
  dailyTimeline: Array<{
    day: number
    actualSpend: number
    projectedSpend: number
    cumulativeSpend: number
    isPast: boolean
    isToday: boolean
    isFuture: boolean
  }>
  /** Array of unpaid scheduled obligations */
  unpaidCommitments: Commitment[]
}

/**
 * Before-and-after comparison payload evaluating a What-If scenario.
 */
export interface SimulationComparison {
  /** Baseline financial metrics before scenario application */
  baseline: FinancialMetrics
  /** Projected financial metrics if scenario is applied */
  simulated: FinancialMetrics
  /** Scenario configuration applied */
  scenario: SimulatedScenario
  /** Quantitative delta vectors */
  deltas: {
    cashBalanceDelta: number
    discretionaryDelta: number
    dailyAllowanceDelta: number
    commitmentsDelta: number
    savingsDelta: number
    monthEndDelta: number
    healthScoreDelta: number
    healthBandChanged: boolean
  }
  /** Structured plain-English impacts */
  explanations: Array<{
    type: 'positive' | 'negative' | 'neutral'
    text: string
  }>
  /** True if proposed scenario survives without triggering cash deficit */
  isAffordable: boolean
  /** Warning advisory if scenario creates financial vulnerability */
  warningNotice?: string
}

/**
 * Contextual recommendation or risk notification produced by the intelligence engine.
 */
export interface FinancialInsight {
  /** Unique insight ID */
  id: string
  /** Headline title */
  title: string
  /** Classification type */
  type: 'risk' | 'opportunity' | 'pacing' | 'savings' | 'subscription'
  /** Urgency severity */
  severity: 'low' | 'medium' | 'high'
  /** Plain-English diagnosis */
  explanation: string
  /** Quantified impact description */
  financialImpact?: string
  /** Primary button action text */
  actionLabel: string
  /** Navigation route destination */
  actionRoute: string
  /** Pre-configured simulation preset */
  scenarioPreset?: Partial<SimulatedScenario>
}

/**
 * Root persistent state schema stored in browser localStorage.
 */
export interface RupeeFlowState {
  /** Schema version for migration compatibility */
  version: number
  /** Active cycle simulation day (1 to 30) */
  currentDay: number
  /** Starting budget baseline (₹10,000) */
  openingBudget: number
  /** Historical transaction ledger */
  transactions: Transaction[]
  /** Scheduled cycle commitments */
  commitments: Commitment[]
  /** Recurring subscription profiles */
  subscriptions: Subscription[]
  /** Dedicated savings goal vaults */
  goals: SavingsGoal[]
  /** Active What-If simulation if engaged */
  activeSimulation: SimulatedScenario | null
  /** ISO timestamp of last modification */
  lastUpdated: string
}
